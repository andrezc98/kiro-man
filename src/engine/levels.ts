/** Layout for level L (1-based): `LEVELS[(L-1) mod 3]`. */
export function levelFor(level: number): LevelDef {
  const n = LEVELS.length;
  const i = (((Math.trunc(level) - 1) % n) + n) % n;
  return LEVELS[i] as LevelDef;
}
