/** Glyph bitmaps: 7 rows of booleans-as-strings, keyed by character. */
export const GLYPHS: Readonly<Record<string, readonly string[]>> = Object.freeze(
  Object.fromEntries(Object.entries(RAW).map(([ch, rows]) => [ch, Object.freeze(rows.split('|'))])),
);

/** The character actually drawn for `ch`: itself if the font has it, otherwise `?` (AP-2.2). */
export function glyphChar(ch: string): string {
  return GLYPHS[ch] === undefined ? '?' : ch;
}

export function glyphRows(ch: string): readonly string[] {
  return GLYPHS[glyphChar(ch)] as readonly string[];
}

/** Pixel width of `text` at `scale` (no trailing gap). */
export function textWidth(text: string, scale = 1): number {
  const n = Array.from(text).length;
  return n === 0 ? 0 : (n * ADVANCE - 1) * scale;
}
